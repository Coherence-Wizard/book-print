import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const json = async file => JSON.parse(await readFile(file, 'utf8'));
const manifest = await json('manifest.json');
if (process.env.GITHUB_REF_TYPE === 'tag' && process.env.GITHUB_REF_NAME !== manifest.version) throw new Error('Tag must equal manifest version, without v prefix.');
assert.deepEqual(manifest, await json('apps/obsidian-plugin/manifest.json'), 'Root and plugin manifests must match.');
const pkg = await json('package.json');
assert.equal(pkg.version, manifest.version, 'Package and manifest versions must match.');
assert.equal(pkg.license, 'SEE LICENSE IN LICENSE');
assert.equal((await json('versions.json'))[manifest.version], manifest.minAppVersion);
const license = await readFile('LICENSE', 'utf8').catch(() => '');
if (!license.trim() || /DRAFT|pending author|awaiting.*approval/i.test(license)) throw new Error('Finalize and approve the root LICENSE before publishing.');
for (const asset of ['main.js', 'manifest.json', 'styles.css']) if (!(await readFile(asset)).length) throw new Error('Missing release asset: ' + asset);
const bundle = await readFile('main.js', 'utf8');
const notices = await readFile('THIRD_PARTY_NOTICES.txt', 'utf8');
assert.ok(notices.trim(), 'Third-party notices must not be empty.');
assert.ok(bundle.startsWith(`/*!\n${license.replaceAll('*/', '* /')}\n${notices.replaceAll('*/', '* /')}*/\n`), 'Both licenses must travel in the installed bundle.');
assert.equal(bundle, await readFile('apps/obsidian-plugin/main.js', 'utf8'));
assert.equal(await readFile('styles.css', 'utf8'), await readFile('apps/obsidian-plugin/styles.css', 'utf8'));
console.log(`Book Print ${manifest.version}: release metadata, installed license notices, and assets verified.`);
